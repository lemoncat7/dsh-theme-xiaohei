import { readFile, writeFile } from 'node:fs/promises'

const sourcePath = new URL('../src/assets/xiaohei-night-clean.webp', import.meta.url)
const idlePath = new URL('../src/assets/character/xiaohei-idle.webp', import.meta.url)
const energyPath = new URL('../src/assets/character/xiaohei-energy.webp', import.meta.url)
const targetPath = new URL('../src/generated-keyart.ts', import.meta.url)
const source = await readFile(sourcePath)
const idle = await readFile(idlePath)
const energy = await readFile(energyPath)
const dataUrl = `data:image/webp;base64,${source.toString('base64')}`
const idleDataUrl = `data:image/webp;base64,${idle.toString('base64')}`
const energyDataUrl = `data:image/webp;base64,${energy.toString('base64')}`

await writeFile(
  targetPath,
  [
    '/** Generated by scripts/embed-assets.mjs. */',
    `export const XIAOHEI_KEY_ART = ${JSON.stringify(dataUrl)}`,
    `export const XIAOHEI_IDLE_SHEET = ${JSON.stringify(idleDataUrl)}`,
    `export const XIAOHEI_ENERGY = ${JSON.stringify(energyDataUrl)}`,
    '',
  ].join('\n'),
  'utf8',
)
